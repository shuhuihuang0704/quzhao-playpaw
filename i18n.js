  var current = "zh";

  function meta(code) {
    for (var i = 0; i < LANGS.length; i++) if (LANGS[i].code === code) return LANGS[i];
    return LANGS[0];
  }

  function readStored() {
    try {
      var v = localStorage.getItem(KEY);
      if (v === "en" || v === "zh" || v === "ja" || v === "ko" || v === "th" || v === "ar") return v;
    } catch (e) {}
    return "zh";
  }

  function writeStored(code) {
    try {
      localStorage.setItem(KEY, code);
    } catch (e) {}
  }

  function getLang() {
    return current;
  }

  function lookup(zh, extra) {
    extra = extra || {};
    var pack = I18N[zh] || {};
    var lang = current;
    if (lang === "zh") return zh;
    return extra[lang] || pack[lang] || extra.en || pack.en || zh;
  }

  function pick(obj) {
    if (!obj) return "";
    if (typeof obj === "string") return lookup(obj);
    return obj[current] || obj.en || obj.zh || "";
  }

  function textOf(el) {
    var t = "";
    for (var i = 0; i < el.childNodes.length; i++) {
      if (el.childNodes[i].nodeType === 3) t += el.childNodes[i].nodeValue;
    }
    return t.replace(/\s+/g, " ").trim();
  }

  function siblingLang(zhEl, lang) {
    var n = zhEl.nextElementSibling;
    while (n && /(?:^|\s)(en|ja|ko|th|ar)(?:\s|$)/.test(n.className || "") && !/(?:^|\s)zh(?:\s|$)/.test(n.className || "")) {
      if ((" " + n.className + " ").indexOf(" " + lang + " ") !== -1) return n;
      n = n.nextElementSibling;
    }
    return null;
  }

  function addLangNode(zhEl, lang, text) {
    if (siblingLang(zhEl, lang)) return;
    var node = zhEl.cloneNode(false);
    node.className = (zhEl.className || "").replace(/\bzh\b/g, lang).replace(/\s+/g, " ").trim();
    if ((" " + node.className + " ").indexOf(" " + lang + " ") === -1) {
      node.className = (node.className + " " + lang).trim();
    }
    node.textContent = text;
    var after = zhEl.nextSibling;
    zhEl.parentNode.insertBefore(node, after);
  }

  function hydrate(root) {
    root = root || d;
    var list = root.querySelectorAll(".zh");
    var i;
    for (i = 0; i < list.length; i++) {
      var zhEl = list[i];
      if (zhEl.getAttribute("data-i18n-skip") === "1") continue;
      if (zhEl.querySelector("button, a, input")) continue;
      var key = textOf(zhEl);
      if (!key) continue;
      var pack = I18N[key] || {};
      var enEl = siblingLang(zhEl, "en");
      var enText = pack.en || (enEl ? textOf(enEl) : "");
      var langs = ["ja", "ko", "th", "ar"];
      var j;
      for (j = 0; j < langs.length; j++) {
        var lang = langs[j];
        var text = pack[lang] || enText;
        if (!text) continue;
        addLangNode(zhEl, lang, text);
      }
    }
  }

  function apply(code) {
    if (!meta(code)) code = "zh";
    current = code;
    writeStored(code);
    var info = meta(code);
    var html = d.documentElement;
    html.setAttribute("data-lang", code);
    html.setAttribute("lang", info.html);
    html.setAttribute("dir", info.dir);
    html.classList.toggle("en", code === "en");
    html.classList.toggle("is-rtl", info.dir === "rtl");
    if (info.title) d.title = info.title;
    var btn = d.getElementById("langBtn");
    if (btn) btn.textContent = info.label;
    var sel = d.getElementById("langSelect");
    if (sel && sel.value !== code) sel.value = code;
    var pop = d.getElementById("langPop");
    if (pop) {
      var buttons = pop.querySelectorAll("[data-lang]");
      var i;
      for (i = 0; i < buttons.length; i++) {
        buttons[i].classList.toggle("is-on", buttons[i].getAttribute("data-lang") === code);
      }
    }
    try {
      w.dispatchEvent(new CustomEvent("qz-lang", { detail: code }));
    } catch (e) {}
  }

  function buildMenu() {
    var sel = d.getElementById("langSelect");
    if (sel) {
      sel.value = current;
      sel.onchange = function () {
        apply(sel.value);
        if (typeof w.qzAfterLang === "function") w.qzAfterLang();
      };
    }
    var btn = d.getElementById("langBtn");
    if (!btn) return;
    var wrap = btn.parentNode;
    if (wrap && !wrap.classList.contains("lang-menu") && !d.getElementById("langSelect")) {
      var menu = d.createElement("div");
      menu.className = "lang-menu";
      wrap.insertBefore(menu, btn);
      menu.appendChild(btn);
      wrap = menu;
    }
    var pop = d.getElementById("langPop");
    if (!pop && !sel) {
      pop = d.createElement("div");
      pop.id = "langPop";
      pop.className = "lang-pop";
      pop.hidden = true;
      var html = "";
      var i;
      for (i = 0; i < LANGS.length; i++) {
        html +=
          '<button type="button" data-lang="' +
          LANGS[i].code +
          '">' +
          LANGS[i].label +
          "</button>";
      }
      pop.innerHTML = html;
      if (wrap) wrap.appendChild(pop);
    }
    if (btn && pop) {
      btn.onclick = function (e) {
        e.preventDefault();
        e.stopPropagation();
        pop.hidden = !pop.hidden;
      };
      pop.onclick = function (e) {
        var t = e.target;
        if (!t || !t.getAttribute) return;
        var code = t.getAttribute("data-lang");
        if (!code) return;
        apply(code);
        pop.hidden = true;
        if (typeof w.qzAfterLang === "function") w.qzAfterLang();
      };
    }
  }

  function boot() {
    current = readStored();
    hydrate(d);
    buildMenu();
    apply(current);
    if (typeof w.qzAfterLang === "function") w.qzAfterLang();
  }

  if (d.readyState === "loading") d.addEventListener("DOMContentLoaded", boot);
  else boot();

